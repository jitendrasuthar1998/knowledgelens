import { GoogleGenAI } from "@google/genai";
import { ChatMessage, ChatResponseBody } from "@/types/chat";

const DEFAULT_SYSTEM_INSTRUCTION = `You are KnowledgeLens, an AI Document Intelligence Assistant.
Your goal is to assist users with clarity, precision, and accuracy.
Keep responses concise, well-structured, and factual.
If you are unsure of an answer, state that clearly rather than inventing facts.`;

function getGeminiClient(): GoogleGenAI {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey.trim() === "" || apiKey === "your_gemini_api_key_here") {
    throw new Error(
      "GEMINI_API_KEY is not configured in environment variables. Please add a valid GEMINI_API_KEY to your .env.local file."
    );
  }

  return new GoogleGenAI({ apiKey });
}

/**
 * Executes a non-streaming chat completion request against Google Gemini.
 * Converts application messages into Gemini's contents schema.
 */
export async function generateGeminiChat(
  messages: Array<Pick<ChatMessage, "role" | "content">>
): Promise<ChatResponseBody> {
  const ai = getGeminiClient();
  const modelName = process.env.GEMINI_MODEL || "gemini-2.5-flash";

  // Map application roles ("user" | "assistant") to Gemini roles ("user" | "model")
  const contents = messages.map((msg) => ({
    role: msg.role === "assistant" ? "model" : "user",
    parts: [{ text: msg.content }],
  }));

  try {
    const response = await ai.models.generateContent({
      model: modelName,
      contents,
      config: {
        systemInstruction: DEFAULT_SYSTEM_INSTRUCTION,
        temperature: 0.2, // Low temperature for deterministic, factual responses
      },
    });

    const replyText = response.text || "No response generated by model.";

    return {
      role: "assistant",
      content: replyText,
      model: modelName,
    };
  } catch (error: unknown) {
    const err = error as { status?: number; message?: string };
    
    // Check for common error types
    if (err.status === 429 || (err.message && err.message.includes("RESOURCE_EXHAUSTED"))) {
      throw new Error("Gemini API rate limit exceeded. Please wait a moment before trying again.");
    }
    
    if (err.status === 400 || (err.message && err.message.includes("API key not valid"))) {
      throw new Error("Invalid Gemini API Key provided. Please verify your key in .env.local.");
    }

    throw new Error(
      err.message || "An unexpected error occurred while communicating with Gemini."
    );
  }
}
